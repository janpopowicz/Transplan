// Optional regeneration step; runtime/builds use the checked-in portable module.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const directory = await mkdtemp(join(tmpdir(), 'transplan-wasm-'));
try {
  const output = join(directory, 'mean-routing.wasm');
  execFileSync(process.env.CLANG || 'clang', ['--target=wasm32', '-O3', '-fno-builtin', '-nostdlib',
    '-Wl,--no-entry', '-Wl,--import-memory', '-Wl,--export-dynamic', '-Wl,--export-all',
    '-Wl,-z,stack-size=65536', 'src/lib/native/meanRouting.c', '-o', output]);
  const bytes = await readFile(output);
  const module = new WebAssembly.Module(bytes);
  if (WebAssembly.Module.imports(module).some((i) => i.module !== 'env' || i.name !== 'memory' || i.kind !== 'memory'))
    throw new Error('The routing kernel may only import linear memory');
  const sourceHash = createHash('sha256').update(await readFile('src/lib/native/meanRouting.c')).digest('hex');
  await writeFile('src/lib/meanRoutingWasm.ts', '// Generated by node scripts/build-mean-routing.mjs from native/meanRouting.c.\n'
    + '// Portable wasm32; no WASI, external functions, or fast-math.\n'
    + '// Source SHA-256: ' + sourceHash + '\n'
    + 'export const MEAN_ROUTING_WASM = "' + bytes.toString('base64') + '";\n');
  console.log('Built mean routing kernel: ' + bytes.length + ' bytes');
} finally { await rm(directory, { recursive: true, force: true }); }
